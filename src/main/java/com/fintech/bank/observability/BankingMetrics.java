package com.fintech.bank.observability;

import com.fintech.bank.entity.OutboxStatus;
import com.fintech.bank.repository.OutboxEventRepository;
import io.micrometer.core.instrument.Counter;
import io.micrometer.core.instrument.Gauge;
import io.micrometer.core.instrument.MeterRegistry;
import io.micrometer.core.instrument.Timer;
import org.springframework.data.domain.Pageable;
import org.springframework.stereotype.Component;

import java.math.BigDecimal;
import java.util.concurrent.TimeUnit;

/**
 * Enterprise Banking Metrics Collector.
 * Provides custom Micrometer metrics for financial transfers, authentication rates,
 * fraud detections, and transactional outbox queue depth.
 */
@Component
public class BankingMetrics {

    private final MeterRegistry meterRegistry;
    private final OutboxEventRepository outboxEventRepository;

    private final Counter completedTransfersCounter;
    private final Counter failedTransfersCounter;
    private final Counter authSuccessCounter;
    private final Counter authFailureCounter;
    private final Counter fraudAlertsCounter;
    private final Timer transferDurationTimer;

    public BankingMetrics(MeterRegistry meterRegistry, OutboxEventRepository outboxEventRepository) {
        this.meterRegistry = meterRegistry;
        this.outboxEventRepository = outboxEventRepository;

        this.completedTransfersCounter = Counter.builder("bank.transfers.count")
                .tag("status", "COMPLETED")
                .description("Total number of successfully executed ledger transfers")
                .register(meterRegistry);

        this.failedTransfersCounter = Counter.builder("bank.transfers.count")
                .tag("status", "FAILED")
                .description("Total number of failed or rolled back transfers")
                .register(meterRegistry);

        this.authSuccessCounter = Counter.builder("bank.auth.events")
                .tag("result", "SUCCESS")
                .description("Total count of successful user authentications")
                .register(meterRegistry);

        this.authFailureCounter = Counter.builder("bank.auth.events")
                .tag("result", "FAILURE")
                .description("Total count of failed user login attempts")
                .register(meterRegistry);

        this.fraudAlertsCounter = Counter.builder("bank.fraud.alerts")
                .description("Total count of high-risk transaction alerts generated by the fraud engine")
                .register(meterRegistry);

        this.transferDurationTimer = Timer.builder("bank.transfers.duration")
                .description("End-to-end latency distribution of funds transfer operations")
                .publishPercentiles(0.50, 0.95, 0.99)
                .publishPercentileHistogram()
                .register(meterRegistry);

        // Gauge for pending outbox events awaiting Kafka publication
        Gauge.builder("bank.outbox.pending.gauge", this, bm -> bm != null ? bm.getPendingOutboxCount() : 0.0)
                .description("Pending transactional outbox events awaiting publication")
                .register(meterRegistry);
    }

    public void recordSuccessfulTransfer(BigDecimal amount, long durationMs) {
        completedTransfersCounter.increment();
        transferDurationTimer.record(durationMs, TimeUnit.MILLISECONDS);
        meterRegistry.summary("bank.transfers.amount").record(amount.doubleValue());
    }

    public void recordFailedTransfer(String failureReason) {
        failedTransfersCounter.increment();
        Counter.builder("bank.transfers.failures")
                .tag("reason", failureReason)
                .register(meterRegistry)
                .increment();
    }

    public void recordAuthSuccess() {
        authSuccessCounter.increment();
    }

    public void recordAuthFailure(String reason) {
        authFailureCounter.increment();
        Counter.builder("bank.auth.failures")
                .tag("reason", reason)
                .register(meterRegistry)
                .increment();
    }

    public void recordFraudAlert(String ruleName, int riskScore) {
        fraudAlertsCounter.increment();
        Counter.builder("bank.fraud.rule.triggers")
                .tag("rule", ruleName)
                .register(meterRegistry)
                .increment();
    }

    public double getPendingOutboxCount() {
        try {
            return outboxEventRepository.findPendingEvents(OutboxStatus.PENDING, Pageable.ofSize(1000)).size();
        } catch (Exception e) {
            return 0.0;
        }
    }
}
